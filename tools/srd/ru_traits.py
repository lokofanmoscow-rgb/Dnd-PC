def shapechanger(desc, n, m):
    i = m['index']
    form = SHAPE.get(i)
    if not form:
        beast = {'bear': 'медведя', 'boar': 'кабана', 'rat': 'гигантскую крысу', 'tiger': 'тигра', 'wolf': 'волка'}
        for k, v in beast.items():
            if i.startswith('were' + k):
                form = 'в гибрид гуманоида и зверя или в ' + v + ' (истинный облик — гуманоид)'
        if i.startswith('vampire'):
            form = SHAPE['vampire-vampire']
    form = form or 'в другой облик'
    return ('Может действием превратиться %s или вернуться в истинный облик. Характеристики, кроме размера, скорости или КД, остаются прежними. '
            'Снаряжение не превращается. После смерти возвращается в истинный облик.') % form


