def false_appearance(desc, n, m):
    mm = re.search(r'indistinguishable from (.+?)\.?$', desc.strip())
    obj = FALSE_APP.get(mm.group(1).strip().rstrip('.'), 'обычного предмета') if mm else 'обычного предмета'
    extra = ' и не летит' if 'flying' in desc else ''
    return 'Пока остаётся неподвижным' + extra + ', неотличим от ' + obj + '.'


ATTACK_WORDS = {'tusk': 'клыком', 'tusks': 'клыками', 'pike': 'пикой', 'ram': 'тараном', 'gore': 'боданием', 'horn': 'рогом', 'claw': 'когтем',
                'hooves': 'копытами', 'stomp': 'топотом', 'bite': 'укусом'}


def charge(desc, n, m):
    dist = n[0]
    am = re.search(r'with (?:a |its )?(\w+)(?: attack)?(?: on| attack)', desc)
    atk = ATTACK_WORDS.get(am.group(1).lower(), 'атакой') if am else 'атакой'
    dm = re.search(r'extra (\d+) \((\d+d\d+(?: ?[+-] ?\d+)?)\) ?(\w+)? damage', desc)
    s = 'Если перемещается как минимум на %s фт. по прямой к цели, а затем в том же ходу попадает по ней %s' % (dist, atk)
    if dm:
        t = dm.group(3)
        s += ', цель получает дополнительно %s (%s) %s' % (dm.group(1), dm.group(2), DT.get(t, 'урона'))
    sv = re.search(r'DC (\d+) Strength', desc)
    if sv:
        if 'pushed' in desc:
            p = re.search(r'pushed up to (\d+)', desc)
            s += '. Если цель — существо, она должна преуспеть в спасброске Силы со Сл %s, иначе будет отброшена на %s фт. и сбита с ног' % (sv.group(1), p.group(1) if p else 10)
        else:
            s += '. Если цель — существо, она должна преуспеть в спасброске Силы со Сл %s, иначе будет сбита с ног' % sv.group(1)
    return s + '.'


def trampling(desc, n, m):
    am = re.search(r'hits it with (?:a |its )?(\w+)', desc)
    atk = ATTACK_WORDS.get(am.group(1).lower(), 'атакой') if am else 'атакой'
    bonus = 'копытами' if 'hooves' in desc.split('bonus action')[0].split('prone')[-1] else 'топотом'
    return ('Если перемещается как минимум на %s фт. по прямой к существу, а затем в том же ходу попадает по нему %s, цель должна преуспеть '
            'в спасброске Силы со Сл %s, иначе будет сбита с ног. По лежащей цели можно бонусным действием совершить атаку %s.') % (n[0], atk, n[1], bonus)


def death_burst(desc, n, m):
    what = {'dust': 'облаком пыли', 'ice': 'осколками льда', 'lava': 'брызгами лавы', 'fire and magma': 'огнём и магмой', 'steam': 'облаком пара'}
    w = next((v for k, v in what.items() if k in desc), 'взрывом')
    rad = n[0]
    dc = re.search(r'DC (\d+) (\w+)', desc)
    s = 'После смерти взрывается %s. Каждое существо в пределах %s фт. ' % (w, rad)
    if 'blinded' in desc:
        s += 'должно преуспеть в спасброске %s со Сл %s, иначе будет ослеплено на 1 минуту (повтор спасброска в каждый свой ход).' % (AB[dc.group(2)], dc.group(1))
        return s
    dm = re.search(r'(\d+) \((\d+d\d+(?: ?[+-] ?\d+)?)\) (\w+) damage', desc)
    s += 'совершает спасбросок %s со Сл %s, получая %s (%s) %s при провале' % (AB[dc.group(2)], dc.group(1), dm.group(1), dm.group(2), DT[dm.group(3)])
    s += ' или половину при успехе.' if 'half' in desc else '.'
    if 'ignited' in desc:
        s += ' Горючие предметы в области воспламеняются.'
    return s


def regeneration(desc, n, m):
    s = 'Восстанавливает %s хитов в начале своего хода' % n[0]
    if 'at least' in desc:
        s += ', если у него есть хотя бы 1 хит'
    if 'sunlight' in desc:
        s += ' и он не на солнце и не в проточной воде'
    if 'acid or fire' in desc:
        s += '. Если получает урон кислотой или огнём, эта особенность не действует в начале его следующего хода'
    if 'radiant' in desc:
        s += '. Если получает урон излучением или святой водой, эта особенность не действует в начале его следующего хода'
    if 'dies only' in desc:
        s += '. Умирает, только если начинает ход с 0 хитов и не регенерирует'
    return s + '.'


